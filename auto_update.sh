#!/bin/bash
set -o pipefail

cd ~/.dotfiles || exit

if [[ $(git branch --show-current) != main ]]; then
    echo "Brewfile updates must run on main." >&2
    exit 1
fi

if ! command -v brew >/dev/null 2>&1; then
    curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh | NONINTERACTIVE=1 /bin/bash || {
        echo "Homebrew installation failed." >&2
        exit 1
    }
fi

# Overwrites the Brewfile with the Mac's most recent installations
brew bundle dump --force || exit $?

# Checks whether the file has changed (diff)
brewfile_status=$(git status -s Brewfile) || exit $?
if [[ -n $brewfile_status ]]; then
    echo "Brewfile has changed, committing to git..." >&2
    git commit --only -m "Brewfile autogenerated: $(date +'%Y-%m-%d')" -- Brewfile || exit $?
fi

unpublished_commits=$(git rev-list origin/main..HEAD) || exit $?
if [[ -n $brewfile_status || -n $unpublished_commits ]]; then
    echo "Pushing unpublished commits to origin/main..." >&2
    git push origin main || exit $?
fi